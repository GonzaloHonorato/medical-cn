CREATE TABLE MED_PACIENTES (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(160) NOT NULL,
  RUT VARCHAR2(20) NOT NULL UNIQUE,
  EDAD NUMBER(3) NOT NULL,
  HABITACION VARCHAR2(30) NOT NULL,
  DIAGNOSTICO VARCHAR2(220) NOT NULL,
  ESTADO VARCHAR2(20) NOT NULL,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE MED_SIGNOS_VITALES (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PACIENTE_ID NUMBER NOT NULL,
  FRECUENCIA_CARDIACA NUMBER(3) NOT NULL,
  PRESION_SISTOLICA NUMBER(3) NOT NULL,
  PRESION_DIASTOLICA NUMBER(3) NOT NULL,
  SATURACION_OXIGENO NUMBER(3) NOT NULL,
  TEMPERATURA NUMBER(4, 1) NOT NULL,
  FRECUENCIA_RESPIRATORIA NUMBER(3) NOT NULL,
  FECHA_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT FK_MED_SIGNOS_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES MED_PACIENTES(ID)
);

CREATE TABLE MED_ALERTAS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PACIENTE_ID NUMBER NOT NULL,
  TIPO VARCHAR2(120) NOT NULL,
  SEVERIDAD VARCHAR2(20) NOT NULL,
  MENSAJE VARCHAR2(300) NOT NULL,
  FECHA_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL,
  ATENDIDA NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_MED_ALERTAS_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES MED_PACIENTES(ID)
);

CREATE TABLE MED_EVENTOS_CLINICOS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PACIENTE_ID NUMBER,
  TIPO VARCHAR2(120) NOT NULL,
  ORIGEN VARCHAR2(120) NOT NULL,
  MENSAJE VARCHAR2(400) NOT NULL,
  SEVERIDAD VARCHAR2(20) NOT NULL,
  VALOR VARCHAR2(80),
  FECHA_EVENTO TIMESTAMP WITH TIME ZONE NOT NULL,
  FECHA_RECEPCION TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT FK_MED_EVENTOS_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES MED_PACIENTES(ID)
);
